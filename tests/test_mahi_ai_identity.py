import os
import unittest
from unittest.mock import patch

from mahi_ai import MahiAIError, _active_reasoning_effort, _agent_chat, _provider_identity_reply, _require_ai


class MahiAIIdentityTests(unittest.TestCase):
    def test_gpt6_reasoning_defaults_to_medium_for_latency(self):
        with patch.dict(os.environ, {}, clear=True):
            self.assertEqual("medium", _active_reasoning_effort("gpt-6-astra"))

    def test_owner_can_override_reasoning_effort(self):
        with patch.dict(os.environ, {"MAHI_AI_REASONING_EFFORT": "low"}):
            self.assertEqual("low", _active_reasoning_effort("gpt-6-astra"))

    def test_agent_uses_mahicloud_identity_without_volunteering_provider_names(self):
        response = {
            "output": [{
                "type": "message",
                "content": [{"type": "output_text", "text": "I'm MahiCloud AI. How can I help?"}],
            }],
        }
        with patch("mahi_ai._require_ai", return_value="test-key"), \
             patch("mahi_ai._openai_request", return_value=response) as request:
            result = _agent_chat("Who are you?", [], "chat")

        self.assertIn("MahiCloud AI", result["reply"])
        instructions = request.call_args.args[0]["instructions"]
        self.assertIn("Never attribute an answer to an underlying model or vendor", instructions)
        self.assertIn("Internal model-routing details aren't exposed in this chat.", instructions)


    def test_provider_identity_questions_get_brand_neutral_reply(self):
        reply = _provider_identity_reply(
            "Are my answers coming from OpenAI or Groq?",
            "I'm powered by OpenAI models.",
        )
        self.assertIn("MahiCloud AI", reply)
        self.assertIn("Internal model-routing details", reply)
        self.assertNotRegex(reply, r"(?i)\b(openai|groq|gpt)\b")

    def test_provider_attribution_is_not_returned_as_the_assistant_identity(self):
        reply = _provider_identity_reply(
            "Who are you?",
            "My answers are generated by GPT-6.",
        )
        self.assertIn("MahiCloud AI", reply)
        self.assertNotRegex(reply, r"(?i)\b(openai|groq|gpt)\b")

    def test_technical_discussion_is_not_blanket_filtered(self):
        reply = _provider_identity_reply(
            "How do I configure an OpenAI API integration in my code?",
            "Add the OpenAI API integration in the server configuration.",
        )
        self.assertIn("OpenAI API integration", reply)

    def test_missing_ai_configuration_uses_brand_neutral_error(self):
        with patch("mahi_ai._openai_key", return_value=""):
            with self.assertRaises(MahiAIError) as context:
                _require_ai()
        self.assertIn("MahiCloud AI", context.exception.message)
        self.assertNotRegex(context.exception.message, r"(?i)\b(openai|groq|gpt)\b")



if __name__ == "__main__":
    unittest.main()
