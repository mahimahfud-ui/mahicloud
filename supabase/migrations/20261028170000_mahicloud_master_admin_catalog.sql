-- MahiCloud native AI and master admin: server-only catalogue and revocable sessions.
create table if not exists public.mahicloud_catalog_items (
  id text primary key check (id ~ '^[a-z0-9][a-z0-9-]{0,47}$'),
  name text not null check (char_length(name) between 1 and 100),
  type text not null check (type in ('apps','movies','tools','social','privacy','music','websites')),
  href text not null check (char_length(href) between 1 and 800),
  subtitle text not null default '' check (char_length(subtitle) <= 180),
  description text not null default '' check (char_length(description) <= 800),
  icon_key text not null default 'grid' check (icon_key in ('grid','movie','film','desktop','sun','clean','users','shield','lock','link','music')),
  icon_url text not null default '' check (char_length(icon_url) <= 800),
  color_primary text not null default '#e50914' check (color_primary ~ '^#[0-9a-fA-F]{6}$'),
  color_secondary text not null default '#7a0309' check (color_secondary ~ '^#[0-9a-fA-F]{6}$'),
  platforms text[] not null default array['Web']::text[] check (cardinality(platforms) between 1 and 10),
  published boolean not null default true,
  position integer not null default 100 check (position between 0 and 100000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists mahicloud_catalog_published_order_idx on public.mahicloud_catalog_items (published, position, name);
alter table public.mahicloud_catalog_items enable row level security;
revoke all on public.mahicloud_catalog_items from anon, authenticated;
grant all on public.mahicloud_catalog_items to service_role;

create table if not exists public.mahicloud_admin_attempts (
  id bigint generated by default as identity primary key,
  ip_hash text not null,
  created_at timestamptz not null default now()
);
create index if not exists mahicloud_admin_attempts_ip_created_idx on public.mahicloud_admin_attempts (ip_hash, created_at desc);
alter table public.mahicloud_admin_attempts enable row level security;
revoke all on public.mahicloud_admin_attempts from anon, authenticated;
grant all on public.mahicloud_admin_attempts to service_role;

create table if not exists public.mahicloud_admin_sessions (
  id uuid primary key default gen_random_uuid(),
  token_hash text not null unique,
  expires_at timestamptz not null,
  revoked_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists mahicloud_admin_sessions_expiry_idx on public.mahicloud_admin_sessions (expires_at);
alter table public.mahicloud_admin_sessions enable row level security;
revoke all on public.mahicloud_admin_sessions from anon, authenticated;
grant all on public.mahicloud_admin_sessions to service_role;

